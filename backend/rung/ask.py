"""Answering questions about the graph — the `/ask` endpoint.

This is a stand-in for Harsh's agent. It routes a natural-language question
to the plain functions in `graph`, `paths` and `sim`, and answers from what
they found. Everything except the routing itself is plain logic, so Harsh
can replace just this module when the real agent is wired up.

The endpoint (`app.main`) consumes `events` and streams the result as Server
Sent Events: one `data: {...}` line per event, exactly as the frontend's chat
panel expects (`tool` while the agent works, `token` for the answer as it is
typed, `path` to light up a chain, and `final` when the answer is complete).
"""
import re

_PATH_WORDS = ("path", "chain", "reach", "escalate")
# Words that route a question to the findings list.
_FINDINGS_WORDS = ("finding", "misconfig", "issue", "risk")
# Words that route to a specialised stub (we don't have the full tool in fallback,
# but can still produce a sensible summary from `context`).
_CHOKE_WORDS = ("fix", "harden", "leverage", "priority", "first")
_TREND_WORDS = ("trend", "worse", "better", "over time", "getting")
_PLAYBOOK_WORDS = ("playbook", "exploit", "attacker", "commands", "poc")
_DEBATE_WORDS = ("red/blue", "red-team", "blue-team", "debate", "attack and fix")


def build_answer(question, context):
    """The final answer: {answer, citations, status, finding}.

    `context` carries whatever the routing needs (`reaching_admin`,
    `findings`, `summary`); the answer itself is plain text.
    """
    q = (question or "").lower()

    if any(word in q for word in _PATH_WORDS):
        reaching = context["reaching_admin"]
        return {
            "answer": _paths_answer(reaching),
            "citations": [],
            "status": None,
            "finding": None,
        }
    if any(word in q for word in _FINDINGS_WORDS):
        tracked = context["findings"]
        # Surface a REGRESSED route as the final event's status/finding, so the
        # UI can raise its banner from a chat answer (contract C5).
        regressed = next((f for f in tracked if f.get("status") == "REGRESSED"), None)
        return {
            "answer": _findings_answer(tracked),
            "citations": [],
            "status": regressed["status"] if regressed else None,
            "finding": regressed,
        }
    if any(word in q for word in _CHOKE_WORDS):
        reaching = context.get("reaching_admin") or []
        if reaching:
            top = reaching[0]
            answer = (
                f"Highest-leverage fix: close the path that reaches cluster-admin from "
                f"{top.get('source', 'the top source')} — removing one choke-point along it "
                f"collapses {len(reaching)} escalation route(s) at once. "
                "Enable the real agent (set BEDROCK_API_KEY or GEMINI_API_KEY) to call "
                "`choke_points` and get the ranked list by betweenness."
            )
        else:
            answer = "No cluster-admin escalations in the current graph — nothing to prioritise."
        return {"answer": answer, "citations": [], "status": None, "finding": None}
    if any(word in q for word in _TREND_WORDS):
        snaps = context.get("snapshots") or []
        if len(snaps) >= 2:
            counts = " → ".join(str(s.get("routes", 0)) for s in reversed(snaps))
            answer = f"Attack-surface route count across snapshots (oldest → newest): {counts}."
        elif snaps:
            answer = f"Only one snapshot on record ({snaps[0].get('routes', 0)} route(s)). Ingest a second one to see the trend."
        else:
            answer = "No snapshot history yet. Run `rung ingest` to record one."
        return {"answer": answer, "citations": [], "status": None, "finding": None}
    if any(word in q for word in _PLAYBOOK_WORDS):
        answer = (
            "Attacker-command playbooks are generated by the `exploit_poc` tool "
            "(templated kubectl/nsenter sequences per edge type). "
            "Enable the real agent (set BEDROCK_API_KEY or GEMINI_API_KEY) to see "
            "the per-step commands for a specific chain."
        )
        return {"answer": answer, "citations": [], "status": None, "finding": None}
    if any(word in q for word in _DEBATE_WORDS):
        answer = (
            "Red/blue debate runs both personas against the live graph: red names the "
            "strongest chain and the first attack commands, blue proposes the smallest "
            "RBAC/policy change that closes it. Both sides are backed by real tool calls "
            "(critical_reach, exploit_poc, simulate_remove, propose_policy). "
            "Enable the real agent (set BEDROCK_API_KEY or GEMINI_API_KEY) to see the voiced transcript."
        )
        return {"answer": answer, "citations": [], "status": None, "finding": None}
    return {
        "answer": (
            "I can explain escalation paths, list what reaches cluster-admin, "
            "describe findings, prioritise fixes, and summarise snapshot trends. "
            "For richer tool-driven answers (exploit playbooks, change simulation, "
            "policy proposals), enable the real agent by setting BEDROCK_API_KEY or GEMINI_API_KEY."
        ),
        "citations": [],
        "status": None,
        "finding": None,
    }


def events(question, context):
    """Yield the SSE events for this question, as plain dicts.

    The frontend appends every `token` to the assistant's message and shows
    the `final` event; `path` lights up the chain on the graph.
    """
    routing = _route(question)

    if routing == "paths":
        yield {"type": "tool", "name": "paths"}
        for entry in context["reaching_admin"]:
            yield {"type": "path", "steps": _path_steps(entry["paths"])}
    elif routing == "findings":
        yield {"type": "tool", "name": "findings"}
    elif routing == "choke":
        yield {"type": "tool", "name": "choke_points"}
    elif routing == "trend":
        yield {"type": "tool", "name": "attack_trend"}
    elif routing == "playbook":
        yield {"type": "tool", "name": "exploit_poc"}
    elif routing == "debate":
        yield {"type": "tool", "name": "red_blue_debate"}
    else:
        yield {"type": "tool", "name": "summary"}

    final = build_answer(question, context)
    for chunk in _tokenize(final["answer"]):
        yield {"type": "token", "text": chunk}
    event = {
        "type": "final",
        "answer": final["answer"],
        "citations": final["citations"],
    }
    # `status`/`finding` are optional in the contract; omit them rather than
    # send null, which `frontend/src/lib/types.ts` does not allow.
    if final.get("status") is not None:
        event["status"] = final["status"]
    if final.get("finding") is not None:
        event["finding"] = final["finding"]
    yield event


def _route(question):
    q = (question or "").lower()
    if any(word in q for word in _PATH_WORDS):
        return "paths"
    if any(word in q for word in _FINDINGS_WORDS):
        return "findings"
    if any(word in q for word in _CHOKE_WORDS):
        return "choke"
    if any(word in q for word in _TREND_WORDS):
        return "trend"
    if any(word in q for word in _PLAYBOOK_WORDS):
        return "playbook"
    if any(word in q for word in _DEBATE_WORDS):
        return "debate"
    return "summary"


def _findings_answer(tracked):
    """A status-by-status summary of the detector's memory."""
    if not tracked:
        return "No tracked routes are reported for this tenant yet."
    counts = {}
    for finding in tracked:
        status = finding.get("status") or "NEW"
        counts[status] = counts.get(status, 0) + 1
    by_status = ", ".join(
        f"{counts[status]} {status}"
        for status in ("REGRESSED", "NEW", "ACCEPTED", "RESOLVED")
        if counts.get(status)
    )
    return f"{len(tracked)} tracked route(s) for this tenant: {by_status}."


def _paths_answer(reaching_admin):
    """A short textual answer pointing at the paths just enumerated."""
    if not reaching_admin:
        return "No identity in this tenant reaches cluster-admin."
    identities = ", ".join(entry["identity"] for entry in reaching_admin)
    return f"{len(reaching_admin)} identity(ies) can escalate, e.g. {identities}."


